import fs from 'node:fs';
const text = fs.readFileSync("D:/User/Desktop/比赛存档/v1/dzrobot_v2"+'/config/robot.yaml','utf8');
const m = text.match(/^\s*tokens:\s*\[(.*?)\]/m);
const toks = m ? m[1].split(/[,\s]+/).map(s=>s.replace(/^["']|["']$/g,'')).filter(Boolean) : [];
const seen = new Map();
toks.forEach((t,i)=>{ const c = t.replace(/^R:/i,'').replace(/\*$/,'').replace(/:PIVOT/i,''); const arr = seen.get(c)||[]; arr.push({i,t}); seen.set(c,arr); });
const dups = [...seen.entries()].filter(([c,arr])=>arr.length>1);
console.log('tokens', toks.length, 'unique', seen.size);
for (const [c,arr] of dups) console.log(c, JSON.stringify(arr.map(x=>x.i+':'+x.t)));
console.log('consecutive dup', toks.filter((t,i)=>i>0 && t===toks[i-1]).length);
console.log('pivot tokens', toks.filter(t=>/:PIVOT/i.test(t)).join(' '));
